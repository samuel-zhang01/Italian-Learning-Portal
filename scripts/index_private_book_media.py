def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--book', action='append', default=[], help='Exact book folder ID; may be repeated')
    parser.add_argument('--repo-root', type=Path, default=ROOT, help='Repository root, primarily for isolated fixtures')
    parser.add_argument('--self-test', action='store_true', help='Use a temporary synthetic repository; never read private books')
    args = parser.parse_args()
    if not args.self_test and not args.book:
        parser.error('Choose --book or --self-test.')
    try:
        if args.self_test:
            require(not args.book, 'self-test-cannot-read-real-books')
            print(json.dumps(self_test()))
        else:
            for book_id in args.book:
                print(json.dumps(build(args.repo_root, book_id)))
        return 0
    except Exception as error:
        reason = str(error) if isinstance(error, PrivateIndexError) else 'offline-index-failed'
        print(json.dumps({'status': 'failed', 'reason': reason, 'error': type(error).__name__}))
        return 1


